// 导出函数
export async function generateReportPDF(
  report: ReportPDFProps['report'],
  analysis: ReportAnalysis,
  topPosts: ReportPDFProps['topPosts']
): Promise<Blob> {
  const doc = (
    <ReportPDFDocument 
      report={report} 
      analysis={analysis} 
      topPosts={topPosts} 
    />
  );
  
  const blob = await pdf(doc).toBlob();
  return blob;
}
